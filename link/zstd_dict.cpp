/* see zstd_dict.h */
const std::vector<u8> &zstd_dict()
{
	static const std::vector<u8> d = [] {
		std::vector<u8> v(header, header + sizeof(header));
		const std::vector<u8> &t = v44_preset();
		v.insert(v.end(), t.begin(), t.end());
		return v;
	}();
	return d;
}

/* see zstd_dict.h */
s32 zstd_dict_header()
{
	return static_cast<s32>(sizeof(header));
}


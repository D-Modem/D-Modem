/* the glyph of ch: its capital for a small letter, '?' for one that the
   font does not have */
const Glyph *glyph(char ch)
{
	if (ch >= 'a' && ch <= 'z')
		ch = static_cast<char>(ch - 'a' + 'A');
	for (const Glyph &g : font)
		if (g.ch == ch)
			return &g;
	for (const Glyph &g : font)
		if (g.ch == '?')
			return &g;
	return nullptr;
}

/* the pel at x of a row set black */
void set_pel(unsigned char *row, s32 x)
{
	row[x >> 3] |= static_cast<unsigned char>(0x80 >> (x & 7));
}


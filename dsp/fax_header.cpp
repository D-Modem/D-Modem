/* (fax_header.h) a blank row of the font's height above and below */
s32 fax_header_rows(s16 fine)
{
	return (FONT_H + 2) * (fine ? 4 : 2);
}

/* (fax_header.h) the header rows first, then the page's own */
s16 fax_header_add(T4Page *p, const char *text)
{
	s16 scale_y = p->fine ? 4 : 2;
	s16 stride = T4_STRIDE(p->width);
	s32 hrows = fax_header_rows(p->fine);
	s32 n = static_cast<s32>(strlen(text));
	s32 max_chars = p->width / CELL - MARGIN;
	std::vector<unsigned char> bits;

	if (p->comps || !p->file.empty() || p->width <= 0)
		return 0;
	if (n > max_chars)
		n = max_chars > 0 ? max_chars : 0;
	if (!alloc_zeroed(bits, static_cast<size_t>(hrows + p->rows) * stride))
		return -1;
	for (s32 k = 0; k < n; k++) {
		const Glyph *g = glyph(text[k]);
		s32 x0 = (MARGIN + k) * CELL;
		if (!g)
			continue;
		for (s16 fy = 0; fy < FONT_H; fy++)
			for (s16 fx = 0; fx < FONT_W; fx++) {
				if (!(g->rows[fy] & (0x10 >> fx)))
					continue;
				for (s16 dy = 0; dy < scale_y; dy++) {
					unsigned char *row = bits.data() +
						static_cast<size_t>((fy + 1) *
						scale_y + dy) * stride;
					for (s16 dx = 0; dx < SCALE_X; dx++)
						set_pel(row, x0 + fx * SCALE_X +
							dx);
				}
			}
	}
	if (p->rows)
		memcpy(bits.data() + static_cast<size_t>(hrows) * stride,
		       p->bits.data(), static_cast<size_t>(p->rows) * stride);
	p->bits.swap(bits);
	p->rows += hrows;
	p->cap = p->rows;
	return 0;
}


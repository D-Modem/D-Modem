/* a grid point (g, in steps of unit / 14 of the V.32bis grid unit)
   through V.32terbo's non-linear encoder, as the Agere modem's fixed
   point code does it: at its transmit scale (V.32bis unit 2048, 18724
   / 128 per 1/14), Y' = Y (1 + z/6 + z^2/120 + z^3/5040) 0.917 with z
   = 0.0098 |Y|^2 in V.32bis units (a sinh(sqrt z)/sqrt z warp: the
   outer points further apart, against the network's companding
   noise).  The result in V.32bis units. */
static constexpr cplx v32t_warp(s8 gx, s8 gy, s32 unit)
{
	s32 x = (gx * unit * 18724) >> 7, y = (gy * unit * 18724) >> 7;
	s32 s = (x * x + y * y) >> 14;
	s = (s * 20649) >> 14;
	s32 c = (s * s) >> 15;
	s32 b = (c * s) >> 15;
	s32 e = (s * 2731 + 137 * c + 3 * b) >> 12;
	s32 g = ((e * 15027) >> 17) + 15027;
	float k = 128.0f / (18724.0f * 14.0f) / 16384.0f;
	return cplx{ static_cast<float>(x * g) * k,
		     static_cast<float>(y * g) * k };
}

/* the N point constellation grid (unit as for v32t_warp) warped */
template <s32 N>
static constexpr V32tPoints<N> v32t_points(const s8 (&grid)[N][2], s32 unit)
{
	V32tPoints<N> t{};
	for (s32 i = 0; i < N; i++)
		t.p[i] = v32t_warp(grid[i][0], grid[i][1], unit);
	return t;
}

